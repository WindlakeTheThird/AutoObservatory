#!/usr/bin/env python3
"""ephcheck_gen.py - generate the Pascal ephemeris reference table from the C++ one.

`make check` runs the same two-epoch reference table through BOTH engines so the
C++ and Free Pascal ports cannot diverge. But until now that table was
hand-transcribed field by field into two files:

    tools/ephcheck.cpp        checks1[] / checks2[]   (24 rows x 6 fields)
    pas/ephcheck_pas.lpr      Checks1 / Checks2

A one-digit typo in a Dec value would make the Pascal check compare against a
different sky than the C++ check while BOTH still printed "ok" -- defeating the
entire purpose of the dual-port check.

This makes the C++ table the single source and emits pas/ephcheck_refs.pas from
it, so the Pascal side can no longer drift. Mirrors how vsop87_gen.py produces
the two VSOP87 tables.

Run via `make check-gui` (before the Pascal ephcheck compiles). Exits 1 if the
C++ table cannot be parsed or the emit fails, so a malformed table fails the
build rather than silently producing an empty reference.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CPP = ROOT / "tools" / "ephcheck.cpp"
OUT = ROOT / "pas" / "ephcheck_refs.pas"

# {"Name", ra, dec, mag, tolDeg, tolMag},   -- the six reference fields
ROW = re.compile(
    r'\{\s*"([^"]+)"\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*,'
    r'\s*(-?[\d.]+)\s*,\s*(-?[\d.]+)\s*\}')

HEADER = """{{ GENERATED by tools/ephcheck_gen.py from tools/ephcheck.cpp - DO NOT EDIT }}
{{ The C++ table in tools/ephcheck.cpp is the single source of truth for the }}
{{ two-epoch ephemeris reference values. Editing that file and running }}
{{ `make check-gui` regenerates this. }}
"""

UNIT = """unit ephcheck_refs;

{$mode objfpc}{$H+}

interface

type
  TCheck = record
    Name: string;
    RAHours, DecDeg, Mag: Double;
    TolDeg, TolMag: Double;
  end;

const
"""

FOOTER = """
implementation

end.
"""


def pascal_num(v):
    """Render a float so the C++ literal round-trips exactly.

    repr() gives the shortest string that parses back to the same double, so the
    two engines are fed bit-identical values rather than merely close ones.
    """
    f = float(v)
    if f == int(f) and abs(f) < 1e15:
        return str(int(f))
    return repr(f)


def parse_cpp(text):
    """Extract (rows1, rows2) from the two Check arrays."""
    out = []
    for name in ("checks1", "checks2"):
        m = re.search(rf"static const Check {name}\[\]\s*=\s*\{{(.*?)\n\}};", text, re.S)
        if not m:
            raise SystemExit(f"could not find {name}[] in {CPP}")
        rows = ROW.findall(m.group(1))
        if not rows:
            raise SystemExit(f"{name}[] parsed but yielded no rows")
        out.append(rows)
    return out


def emit(rows1, rows2):
    parts = [HEADER, UNIT]
    for idx, (rows, label, stamp) in enumerate(
            ((rows1, "Checks1", "2026-09-23 00:00 UT"),
             (rows2, "Checks2", "2027-03-23 00:00 UT"))):
        parts.append(f"\n  // {label}: {stamp}, JPL Horizons geocentric apparent\n")
        parts.append(f"  {label}: array[0..{len(rows) - 1}] of TCheck = (\n")
        for i, (n, ra, dec, mag, td, tm) in enumerate(rows):
            # The format string already emits the record's closing ')'. So a non-final row
            # needs only ',' and the final row needs ');' to also close the
            # array literal opened by "of TCheck = (".
            tail = ");" if i == len(rows) - 1 else ","
            parts.append(
                f"    (Name:'{n}'; RAHours:{pascal_num(ra)}; DecDeg:{pascal_num(dec)}; "
                f"Mag:{pascal_num(mag)}; TolDeg:{pascal_num(td)}; TolMag:{pascal_num(tm)})"
                + tail + "\n")
    parts.append(FOOTER)
    return "".join(parts)


def main():
    if not CPP.exists():
        print(f"FAIL missing {CPP}")
        return 1
    rows1, rows2 = parse_cpp(CPP.read_text(encoding="utf-8"))

    n1, n2 = len(rows1), len(rows2)
    if n1 != n2:
        print(f"FAIL epoch tables differ in length: {n1} vs {n2}")
        return 1

    OUT.write_text(emit(rows1, rows2), encoding="utf-8")

    names1 = [r[0] for r in rows1]
    names2 = [r[0] for r in rows2]
    if names1 != names2:
        print(f"FAIL object sets differ between epochs: {names1} vs {names2}")
        return 1

    print(f"ok   wrote {OUT.relative_to(ROOT)} ({n1} rows/epoch from {CPP.relative_to(ROOT)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())